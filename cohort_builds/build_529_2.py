def load_bib():
    txt = open(MD, encoding="utf-8").read()
    idx = txt.rfind("## Список литературы")
    block = txt[idx:]
    bib = {}
    n = 0
    for line in block.splitlines()[1:]:
        if line.startswith("- "):
            n += 1
            bib[n] = line[2:].strip()
        elif bib and line.strip() and not line.startswith(("#", "|")):
            break
    return bib

def cite(refs, bib):
    if not refs:
        return None
    m = re.match(r"\[?(\d+)", str(refs[0]))
    if not m:
        return None
    e = bib.get(int(m.group(1)))
    return re.sub(r"\s+", " ", e)[:300] if e else None

