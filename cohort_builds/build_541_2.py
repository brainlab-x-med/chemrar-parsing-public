def cite(refs):
    if not refs: return None
    m=re.match(r"\[?\[?(\d+)",str(refs[0]))
    if not m: return None
    e=bib.get(int(m.group(1)))
    return re.sub(r"\s+"," ",e)[:300] if e else None
