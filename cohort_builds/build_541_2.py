def load_bib():
    txt=open(MD,encoding="utf-8").read(); i=txt.rfind("## Список литературы"); bib={}; n=0
    for line in txt[i:].splitlines()[1:]:
        if line.startswith("- "): n+=1; bib[n]=line[2:].strip()
        elif bib and line.strip() and not line.startswith(("#","|")): break
    return bib
