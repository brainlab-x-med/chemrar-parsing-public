def R(cohort, line, ttype, name, drugs, stage, refs, sec, tbl=None, uur=None, udd=None,
      ecog=None, bio=None, spec="", maint=None, page=None):
    _n[0] += 1
    rid = f"R{_n[0]:02d}"
    refs = [str(x) for x in refs]
    rows.append({
        "cohort_id": cohort,
        "row_id": rid,
        "disease": DISEASE,
        "treatment": {"line_stage": line, "therapy_type": ttype, "regimen_name": name},
        "drugs": drugs,
        "indications": {"stage": stage, "ecog": ecog, "biomarkers": bio or []},
        "evidence": {"uur": uur, "udd": udd},
        "source": {"page": page, "section": sec, "table": tbl,
                   "references": refs, "citation": cite(int(refs[0])) if refs and refs[0].isdigit() else None},
        "special_conditions": spec,
        "maintenance_therapy": maint,
    })
    return rows[-1]


