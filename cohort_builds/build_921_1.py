def cite(ref_id):
    """Resolve a reference id -> 'Первые авторы et al. Журнал. ‒ Год'."""
    e = REFS.get(ref_id)
    if not e:
        return None
    head, _, tail = e.partition(" // ")
    authors = ", ".join(x.strip() for x in head.split(",")[:3])
    journal = tail.split("‒")[0].strip().rstrip(".")
    ym = re.search(r"(19|20)\d{2}", tail)
    year = ym.group(0) if ym else ""
    c = f"{authors} et al. {journal}"
    if year:
        c += f". ‒ {year}"
    return c


